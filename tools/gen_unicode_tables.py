"""Generate src/unicode_data.inc: the letter and number code point ranges GPT-2's
pre-tokenizer splits on, from Python's Unicode database.

Run after a Python upgrade changes unicodedata.unidata_version, then commit the output.
"""

import sys
import unicodedata
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "src" / "unicode_data.inc"


def ranges(category_prefix: str) -> list[tuple[int, int]]:
    """Inclusive [first, last] runs of code points whose general category starts with the prefix."""
    runs: list[tuple[int, int]] = []
    for code_point in range(sys.maxunicode + 1):
        if not unicodedata.category(chr(code_point)).startswith(category_prefix):
            continue
        if runs and runs[-1][1] == code_point - 1:
            runs[-1] = (runs[-1][0], code_point)
        else:
            runs.append((code_point, code_point))
    return runs


def table(name: str, runs: list[tuple[int, int]]) -> str:
    rows = "\n".join(f"    {{.first = 0x{first:x}, .last = 0x{last:x}}}," for first, last in runs)
    return f"constexpr std::array<CodePointRange, {len(runs)}> {name} = {{{{\n{rows}\n}}}};\n"


def main() -> None:
    text = (
        f"// Generated by tools/gen_unicode_tables.py from Unicode {unicodedata.unidata_version}."
        " Do not edit.\n\n"
        + table("kLetterRanges", ranges("L"))
        + "\n"
        + table("kNumberRanges", ranges("N"))
    )
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
